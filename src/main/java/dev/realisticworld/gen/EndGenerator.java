package dev.realisticworld.gen;

import dev.realisticworld.Settings;
import org.bukkit.HeightMap;
import org.bukkit.Material;
import org.bukkit.World;
import org.bukkit.generator.BiomeProvider;
import org.bukkit.generator.BlockPopulator;
import org.bukkit.generator.ChunkGenerator;
import org.bukkit.generator.WorldInfo;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Random;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;

public final class EndGenerator extends ChunkGenerator {
    private final Settings settings;
    private final Map<UUID, EndSampler> samplers = new ConcurrentHashMap<>();
    private final BiomeProvider provider = new EndBiomeProvider(this);

    public EndGenerator(Settings settings) {
        this.settings = settings;
    }

    /** Zone key at a position (chorus_forest, ...), or "main_island" inside the unchanged centre area. */
    public String zoneKeyAt(WorldInfo w, int x, int z) {
        EndSampler s = sampler(w);
        if (!settings.endCustomBiomes()) return s.biome(x, z) == org.bukkit.block.Biome.THE_END ? "main_island" : "outer_end";
        if (Math.hypot(x, z) < s.zoneStart()) return "main_island";
        return s.spot(x, z).zone().key;
    }

    public static java.util.List<String> zoneKeys() {
        return dev.realisticworld.Settings.biomeKeys("end");
    }

    EndSampler sampler(WorldInfo w) {
        return samplers.computeIfAbsent(w.getUID(), id -> new EndSampler(w.getSeed(), settings));
    }

    @Override
    public void generateNoise(@NotNull WorldInfo w, @NotNull Random rnd, int cx, int cz, @NotNull ChunkData d) {
        EndSampler s = sampler(w);
        int minY = w.getMinHeight(), maxY = w.getMaxHeight() - 1;
        Noise.Vertical sv = new Noise.Vertical();
        for (int x = 0; x < 16; x++) {
            for (int z = 0; z < 16; z++) {
                int wx = cx * 16 + x, wz = cz * 16 + z;
                EndSampler.Col c = s.col(wx, wz);
                int lo = Math.max(minY, c.bottom()), hi = Math.min(maxY, c.top());
                if (c.ground() && hi >= lo) d.setRegion(x, lo, z, x + 1, hi + 1, z + 1, Material.END_STONE);
                if (c.shards() && settings.endShards()) {
                    s.shardColumn(sv, wx, wz);
                    for (int y = 30; y <= 110 && y <= maxY; y++) {
                        if ((!c.ground() || y < lo || y > hi) && s.shard(sv, y)) {
                            d.setBlock(x, y, z, Material.END_STONE);
                        }
                    }
                }
            }
        }
    }

    /**
     * Surface blocks of the new End zones. Everything closer than {@link EndSampler#zoneStart()} to the centre
     * (main island and its surroundings) is skipped and stays as generated by generateNoise.
     */
    @Override
    public void generateSurface(@NotNull WorldInfo w, @NotNull Random rnd, int cx, int cz, @NotNull ChunkData d) {
        if (!settings.endCustomBiomes()) return;
        EndSampler s = sampler(w);
        int minY = w.getMinHeight(), maxY = w.getMaxHeight() - 1;
        for (int x = 0; x < 16; x++) {
            for (int z = 0; z < 16; z++) {
                int wx = cx * 16 + x, wz = cz * 16 + z;
                if (Math.hypot(wx, wz) < s.zoneStart()) continue;
                EndSampler.Col c = s.col(wx, wz);
                if (!c.ground()) continue;
                int top = c.top();
                if (top < minY + 3 || top > maxY) continue;
                if (d.getType(x, top, z) != Material.END_STONE) continue;
                EndSampler.Spot spot = s.spot(wx, wz);
                if (!spot.zone().custom) continue;
                double p = s.patch(wx, wz), p2 = s.patch2(wx, wz);
                Material m = topMaterial(spot, p, p2);
                d.setBlock(x, top, z, m);
                Material sub = subMaterial(spot, m, p);
                int layers = spot.zone() == EndZone.OBSIDIAN_WASTES ? 2 : 1;
                if (sub != Material.END_STONE) {
                    for (int k = 1; k <= layers; k++) {
                        if (d.getType(x, top - k, z) == Material.END_STONE) d.setBlock(x, top - k, z, sub);
                    }
                }
            }
        }
    }

    private static Material topMaterial(EndSampler.Spot spot, double p, double p2) {
        return switch (spot.zone()) {
            case CHORUS_FOREST -> p2 > 0.55 ? Material.PURPUR_BLOCK : Material.END_STONE;
            case CRYSTAL_FIELDS -> p2 > 0.5 ? Material.AMETHYST_BLOCK : (p > 0.15 ? Material.CALCITE : Material.END_STONE);
            case OBSIDIAN_WASTES -> p2 > 0.62 ? Material.END_STONE : (p > 0.45 ? Material.CRYING_OBSIDIAN : Material.OBSIDIAN);
            case ENDER_DUNES -> p > 0.3 ? Material.CALCITE : Material.END_STONE;
            case PURPUR_RUINS -> p > 0.25 ? Material.END_STONE_BRICKS : (p2 > 0.55 ? Material.PURPUR_BLOCK : Material.END_STONE);
            case VOID_RIFTS -> spot.rim() ? (p > 0 ? Material.CRYING_OBSIDIAN : Material.OBSIDIAN) : Material.END_STONE;
            default -> Material.END_STONE;
        };
    }

    private static Material subMaterial(EndSampler.Spot spot, Material top, double p) {
        return switch (spot.zone()) {
            case CRYSTAL_FIELDS -> p > 0.15 ? Material.CALCITE : Material.END_STONE;
            case OBSIDIAN_WASTES -> top == Material.END_STONE ? Material.END_STONE : Material.OBSIDIAN;
            case VOID_RIFTS -> spot.rim() ? Material.OBSIDIAN : Material.END_STONE;
            default -> Material.END_STONE;
        };
    }

    /** Text for /rw info. */
    public String describe(World w, int x, int z) {
        EndSampler s = sampler(w);
        double dist = Math.hypot(x, z);
        EndSampler.Col c = s.col(x, z);
        String zone = !settings.endCustomBiomes() ? "off"
                : dist < s.zoneStart() ? "none (main island area, unchanged)" : s.spot(x, z).zone().key;
        return String.format(Locale.ROOT, "biome=%s zone=%s ground=%s top=%d distance=%.0f",
                s.biome(x, z), zone, c.ground(), c.top(), dist);
    }

    @Override
    public boolean shouldGenerateDecorations(@NotNull WorldInfo w, @NotNull Random r, int cx, int cz) {
        return true;
    }

    @Override
    public boolean shouldGenerateMobs(@NotNull WorldInfo w, @NotNull Random r, int cx, int cz) {
        return true;
    }

    @Override
    public boolean shouldGenerateStructures(@NotNull WorldInfo w, @NotNull Random r, int cx, int cz) {
        return settings.structures();
    }

    @Override
    public int getBaseHeight(@NotNull WorldInfo w, @NotNull Random rnd, int x, int z, @NotNull HeightMap heightMap) {
        EndSampler.Col c = sampler(w).col(x, z);
        return c.ground() ? c.top() + 1 : w.getMinHeight();
    }

    @Override
    public @Nullable BiomeProvider getDefaultBiomeProvider(@NotNull WorldInfo w) {
        return provider;
    }

    @Override
    public @NotNull List<BlockPopulator> getDefaultPopulators(@NotNull World world) {
        return List.of(new EndPopulator(this, settings, world));
    }
}
