package dev.realisticworld;

import dev.realisticworld.gen.MountainSites;
import dev.realisticworld.gen.MountainSites.Site;
import dev.realisticworld.gen.RealisticChunkGenerator;
import org.bukkit.Location;
import org.bukkit.World;
import org.bukkit.command.CommandSender;
import org.bukkit.configuration.file.YamlConfiguration;
import org.bukkit.entity.Player;
import org.bukkit.event.EventHandler;
import org.bukkit.event.Listener;
import org.bukkit.event.world.WorldLoadEvent;
import org.bukkit.generator.structure.Structure;
import org.bukkit.util.StructureSearchResult;

import java.io.File;
import java.io.IOException;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Finds the strongholds of a world, decides by chance which of them get the mountain terrain, stores the sites
 * per world and offers the /rw mountain commands.
 *
 * The terrain itself is generated by the chunk generator from the site list; this class only maintains the list.
 * Chunks that are already generated are never changed.
 */
public final class MountainManager implements Listener {
    private static final int SCAN_STEP = 768;
    private static final long SCAN_LIMIT_NANOS = 20_000_000_000L;

    private final RealisticWorldPlugin plugin;
    private final RealisticChunkGenerator generator;
    private final Settings settings;
    private final Set<UUID> attached = ConcurrentHashMap.newKeySet();
    private final Set<UUID> scanned = ConcurrentHashMap.newKeySet();

    MountainManager(RealisticWorldPlugin plugin, RealisticChunkGenerator generator, Settings settings) {
        this.plugin = plugin;
        this.generator = generator;
        this.settings = settings;
    }

    /** Worlds that were loaded before this plugin registered its listener. */
    void attachLoadedWorlds() {
        for (World w : plugin.getServer().getWorlds()) attach(w);
    }

    @EventHandler
    public void onWorldLoad(WorldLoadEvent e) {
        attach(e.getWorld());
    }

    private void attach(World w) {
        if (!settings.mountainsEnabled() || w.getGenerator() != generator) return;
        if (!attached.add(w.getUID())) return;
        loadFile(w, generator.sites(w));
        // after startup: the first locate call needs the world to be fully set up
        plugin.getServer().getScheduler().runTask(plugin, () -> {
            String r = discover(w, false);
            if (r != null) plugin.getLogger().info("[" + w.getName() + "] " + r);
        });
    }

    // ------------------------------------------------------------------ persistence

    private File file(World w) {
        return new File(plugin.getDataFolder(), "mountains/" + w.getName().replaceAll("[^A-Za-z0-9_.-]", "_") + ".yml");
    }

    private void loadFile(World w, MountainSites ms) {
        File f = file(w);
        if (!f.exists()) return;
        YamlConfiguration yml = YamlConfiguration.loadConfiguration(f);
        if (yml.getBoolean("scanned", false)) scanned.add(w.getUID());
        List<Site> list = new ArrayList<>();
        for (String line : yml.getStringList("sites")) {
            String[] p = line.split(";");
            if (p.length != 3) continue;
            try {
                list.add(new Site(Integer.parseInt(p[1].trim()), Integer.parseInt(p[2].trim()), p[0].trim()));
            } catch (NumberFormatException ex) {
                plugin.getLogger().warning("Ignoring bad entry in " + f.getName() + ": " + line);
            }
        }
        ms.setSites(list);
        generator.sampler(w).sitesChanged();
        if (!list.isEmpty()) plugin.getLogger().info("[" + w.getName() + "] loaded " + list.size() + " mountain site(s).");
    }

    private void saveFile(World w) {
        MountainSites ms = generator.sites(w);
        YamlConfiguration yml = new YamlConfiguration();
        yml.set("scanned", scanned.contains(w.getUID()));
        List<String> lines = new ArrayList<>();
        for (Site s : ms.sites()) lines.add(s.source() + ";" + s.x() + ";" + s.z());
        yml.set("sites", lines);
        File f = file(w);
        File parent = f.getParentFile();
        if (parent != null && !parent.exists() && !parent.mkdirs()) {
            plugin.getLogger().warning("Could not create " + parent);
            return;
        }
        try {
            yml.save(f);
        } catch (IOException e) {
            plugin.getLogger().warning("Could not save " + f.getName() + ": " + e.getMessage());
        }
    }

    // ------------------------------------------------------------------ stronghold discovery

    /** Deterministic roll per stronghold, independent of the order strongholds are found in. */
    private boolean rolls(long seed, int cx, int cz) {
        long h = seed ^ (cx * 0x9E3779B97F4A7C15L) ^ (cz * 0xC2B2AE3D27D4EB4FL) ^ 0x5DEECE66DL;
        h ^= h >>> 30;
        h *= 0xBF58476D1CE4E5B9L;
        h ^= h >>> 27;
        h *= 0x94D049BB133111EBL;
        h ^= h >>> 31;
        double r = (h >>> 11) * (1.0 / (1L << 53));
        return r < settings.mountainChance();
    }

    /** Chunk of the stronghold nearest to a block position, or null if the server reports none. */
    private int[] nearestStronghold(World w, int x, int z) {
        StructureSearchResult r = w.locateNearestStructure(new Location(w, x, 64, z), Structure.STRONGHOLD, 100, false);
        if (r == null) return null;
        Location l = r.getLocation();
        // the reported block is somewhere inside the start chunk
        return new int[]{Math.floorDiv(l.getBlockX(), 16), Math.floorDiv(l.getBlockZ(), 16)};
    }

    /**
     * Looks up the strongholds around the world origin by asking the server for the nearest stronghold from a
     * grid of points (every stronghold is the nearest one for the points around it), rolls the chance for each
     * and adds the sites. Runs on the main thread. After the first call for a world the biome provider stops
     * hiding the sites' biomes.
     *
     * @return a one line report, or null if nothing had to be done
     */
    String discover(World w, boolean rescan) {
        MountainSites ms = generator.sites(w);
        String report = null;
        try {
            if (rescan || !scanned.contains(w.getUID())) {
                report = scan(w, ms);
                saveFile(w);
            }
        } catch (Throwable t) {
            report = "Stronghold lookup failed: " + t;
            plugin.getLogger().warning("[" + w.getName() + "] " + report
                    + " Mountain sites can still be added with /rw mountain.");
        } finally {
            ms.setSuppressed(false);
            generator.sampler(w).sitesChanged();
        }
        return report;
    }

    private String scan(World w, MountainSites ms) {
        long start = System.nanoTime();
        int radius = settings.mountainScanRadius();
        Set<Long> seen = new HashSet<>();
        int queries = 0, empty = 0, added = 0;
        boolean aborted = false;
        outer:
        for (int qx = -radius; qx <= radius; qx += SCAN_STEP) {
            for (int qz = -radius; qz <= radius; qz += SCAN_STEP) {
                if ((double) qx * qx + (double) qz * qz > (double) (radius + SCAN_STEP) * (radius + SCAN_STEP)) continue;
                if (System.nanoTime() - start > SCAN_LIMIT_NANOS) {
                    aborted = true;
                    break outer;
                }
                queries++;
                int[] ch = nearestStronghold(w, qx, qz);
                if (ch == null) {
                    empty++;
                    continue;
                }
                if (!seen.add(((long) ch[0] << 32) ^ (ch[1] & 0xffffffffL))) continue;
                if (!rolls(w.getSeed(), ch[0], ch[1])) continue;
                Site s = new Site(ch[0] * 16 + 4, ch[1] * 16 + 4, "stronghold");
                if (ms.add(s) == s) added++;
            }
        }
        if (!aborted && !seen.isEmpty()) scanned.add(w.getUID());
        String r = "Found " + seen.size() + " stronghold(s) within about " + radius + " blocks (" + queries
                + " lookups), " + added + " new mountain site(s) (chance " + Math.round(settings.mountainChance() * 100) + "%).";
        if (aborted) r += " The lookup was stopped after 20 seconds; run /rw mountain scan again.";
        if (seen.isEmpty()) r += " The server returned no stronghold; check the log, or use /rw mountain here.";
        else if (empty > 0) r += " " + empty + " lookups returned nothing.";
        return r;
    }

    // ------------------------------------------------------------------ commands

    private World contextWorld(CommandSender sender) {
        if (sender instanceof Player p && p.getWorld().getGenerator() == generator) return p.getWorld();
        for (World w : plugin.getServer().getWorlds()) {
            if (w.getGenerator() == generator) return w;
        }
        return null;
    }

    /** Chunks of a site's area that exist already: {generated, total}. */
    private int[] generatedChunks(World w, Site s) {
        MountainSites ms = generator.sites(w);
        double r = ms.outerRadius();
        int gen = 0, total = 0;
        for (int cx = Math.floorDiv((int) (s.x() - r), 16); cx <= Math.floorDiv((int) (s.x() + r), 16); cx++) {
            for (int cz = Math.floorDiv((int) (s.z() - r), 16); cz <= Math.floorDiv((int) (s.z() + r), 16); cz++) {
                double dx = cx * 16 + 8 - s.x(), dz = cz * 16 + 8 - s.z();
                if (dx * dx + dz * dz > r * r) continue;
                total++;
                if (w.isChunkGenerated(cx, cz)) gen++;
            }
        }
        return new int[]{gen, total};
    }

    private void announce(CommandSender sender, World w, Site s) {
        int[] g = generatedChunks(w, s);
        sender.sendMessage("Mountain site at x=" + s.x() + " z=" + s.z() + " (" + s.source() + ", radius about "
                + (int) generator.sites(w).outerRadius() + " blocks).");
        if (g[0] > 0) {
            sender.sendMessage(g[0] + " of " + g[1] + " chunks in that area are already generated and keep their old terrain. "
                    + "Only new chunks get the mountains; delete the region files of the area to regenerate it.");
        } else {
            sender.sendMessage("None of the " + g[1] + " chunks in that area exist yet; the mountains appear when they are generated.");
        }
    }

    private void changed(World w) {
        generator.sampler(w).sitesChanged();
        saveFile(w);
    }

    void command(CommandSender sender, String[] a) {
        if (!settings.mountainsEnabled()) {
            sender.sendMessage("Stronghold mountains are disabled (overworld.stronghold-mountains.enabled).");
            return;
        }
        World w = contextWorld(sender);
        if (w == null) {
            sender.sendMessage("No world with the RealisticWorld overworld generator found.");
            return;
        }
        MountainSites ms = generator.sites(w);
        String sub = a.length > 1 ? a[1].toLowerCase(Locale.ROOT) : "list";
        Player p = sender instanceof Player pl ? pl : null;
        switch (sub) {
            case "list" -> {
                Site[] sites = ms.sites();
                if (sites.length == 0) sender.sendMessage("No mountain sites in " + w.getName() + ".");
                for (int i = 0; i < sites.length; i++) {
                    Site s = sites[i];
                    String d = p == null ? "" : " (" + (int) Math.hypot(s.x() - p.getLocation().getX(), s.z() - p.getLocation().getZ()) + " blocks away)";
                    sender.sendMessage("#" + (i + 1) + " x=" + s.x() + " z=" + s.z() + " " + s.source() + d);
                }
            }
            case "here" -> {
                if (p == null) {
                    sender.sendMessage("/rw mountain here (players only); use /rw mountain at <x> <z> from the console.");
                    return;
                }
                addSite(sender, w, new Site(p.getLocation().getBlockX(), p.getLocation().getBlockZ(), "command"));
            }
            case "at" -> {
                if (a.length < 4) {
                    sender.sendMessage("/rw mountain at <x> <z>");
                    return;
                }
                try {
                    addSite(sender, w, new Site(Integer.parseInt(a[2]), Integer.parseInt(a[3]), "command"));
                } catch (NumberFormatException e) {
                    sender.sendMessage("x and z must be whole numbers.");
                }
            }
            case "stronghold" -> {
                int ox = p == null ? 0 : p.getLocation().getBlockX(), oz = p == null ? 0 : p.getLocation().getBlockZ();
                int[] ch;
                try {
                    ch = nearestStronghold(w, ox, oz);
                } catch (Throwable t) {
                    sender.sendMessage("Stronghold lookup failed: " + t);
                    return;
                }
                if (ch == null) {
                    sender.sendMessage("The server did not report a stronghold.");
                    return;
                }
                addSite(sender, w, new Site(ch[0] * 16 + 4, ch[1] * 16 + 4, "stronghold-command"));
            }
            case "scan" -> {
                String r = discover(w, true);
                sender.sendMessage(r == null ? "Nothing to do." : r);
            }
            case "remove" -> removeSite(sender, w, a, p);
            case "tp" -> {
                if (p == null || a.length < 3) {
                    sender.sendMessage("/rw mountain tp <number from /rw mountain list> (players only)");
                    return;
                }
                Site[] sites = ms.sites();
                try {
                    int i = Integer.parseInt(a[2]) - 1;
                    if (i < 0 || i >= sites.length) {
                        sender.sendMessage("No such site.");
                        return;
                    }
                    Site s = sites[i];
                    int y = w.getHighestBlockYAt(s.x(), s.z()) + 1;
                    p.teleport(new Location(w, s.x() + 0.5, y, s.z() + 0.5));
                } catch (NumberFormatException e) {
                    sender.sendMessage("The site number must be a number.");
                }
            }
            default -> sender.sendMessage("/rw mountain <list|here|at <x> <z>|stronghold|scan|remove [x z]|tp <n>>");
        }
    }

    private void addSite(CommandSender sender, World w, Site s) {
        MountainSites ms = generator.sites(w);
        Site got = ms.add(s);
        if (got != s) {
            sender.sendMessage("There is already a mountain site in this chunk (x=" + got.x() + " z=" + got.z() + ").");
            return;
        }
        changed(w);
        announce(sender, w, s);
    }

    private void removeSite(CommandSender sender, World w, String[] a, Player p) {
        MountainSites ms = generator.sites(w);
        double qx, qz;
        if (a.length >= 4) {
            try {
                qx = Integer.parseInt(a[2]);
                qz = Integer.parseInt(a[3]);
            } catch (NumberFormatException e) {
                sender.sendMessage("x and z must be whole numbers.");
                return;
            }
        } else if (p != null) {
            qx = p.getLocation().getX();
            qz = p.getLocation().getZ();
        } else {
            sender.sendMessage("/rw mountain remove <x> <z>");
            return;
        }
        Site best = null;
        double bd = Double.MAX_VALUE;
        for (Site s : ms.sites()) {
            double d = Math.hypot(s.x() - qx, s.z() - qz);
            if (d < bd) {
                bd = d;
                best = s;
            }
        }
        if (best == null || bd > ms.outerRadius()) {
            sender.sendMessage("No mountain site within " + (int) ms.outerRadius() + " blocks of that position.");
            return;
        }
        ms.remove(best);
        changed(w);
        sender.sendMessage("Removed the site at x=" + best.x() + " z=" + best.z()
                + ". Chunks that were generated with it keep the mountains.");
    }

    List<String> complete(String[] args) {
        if (args.length == 2) {
            String pre = args[1].toLowerCase(Locale.ROOT);
            List<String> out = new ArrayList<>();
            for (String s : List.of("list", "here", "at", "stronghold", "scan", "remove", "tp")) {
                if (s.startsWith(pre)) out.add(s);
            }
            return out;
        }
        return List.of();
    }
}
